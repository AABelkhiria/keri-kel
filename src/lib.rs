//! KERI key event log validation: accepting events into a log and deriving key state.
//!
//! [`event`] reads a key event off the wire and checks what a key event must commit to on its
//! own: its SAID and, for an inception, its identifier prefix. [`kever`] holds one identifier's key
//! state and decides whether the next signed event extends it: an inception starts a log, and a
//! rotation or interaction is accepted only when it follows the latest event, is signed to the
//! current threshold and, for a rotation, also to the threshold committed in the prior event's next
//! keys. A witnessed event must also carry enough witness signatures.
//!
//! This ports keripy's `Kever` (`src/keri/core/eventing.py`), the canonical KERI validator, and is
//! verified against fixtures keripy generated by validating the same logs.
//!
//! Nothing here reads a clock, a database or a network. The first-seen time is an argument, the
//! state lives in the value, and what to do with an event that is not accepted yet, keep it in an
//! escrow or drop it, is the caller's: an error says whether waiting could help
//! ([`KelError::escrow`]).
//!
//! [`kevery`] holds many identifiers' logs: it routes each arriving message to the right log,
//! applies receipts, approves delegated events against their delegators' logs, and keeps events
//! that arrive out of order, are short of signatures or of their delegator's approval, with
//! everything offered for them, until more arrive. An event contradicting an accepted one is kept
//! aside as likely duplicitous.
//!
//! A recovery rotation, signed with the keys the latest establishment event committed to, may
//! supersede the interactions accepted since; [`Kevery`] keeps the superseded events apart. A
//! delegated rotation may supersede the latest delegated rotation when its delegator approves it
//! later, under keripy's rules as its code applies them.
//!
//! Receipts from validators, transferable identifiers that receipt others' events, are verified
//! against the keys of the validator's own establishment event they name, which [`Kevery`] must hold
//! too, and stored with the event.

#![forbid(unsafe_code)]

